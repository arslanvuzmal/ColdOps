"""The knowledge base: what ColdOps knows, as Markdown, generated from the code.

Programme item L. Everything ColdOps knows -- what each website finding means,
costs and how it is fixed; how each industry is approached; how a lead is
scored; how a reply is read; when mail is refused -- lives in the code that
acts on it. That is the right place for it to *live*, and the wrong place for a
person to *read* it. These files are the readable copy.

Generated, never hand-edited, for the same reason ``.env.example`` is: a
hand-kept copy drifts from what the system actually does, and a knowledge base
that is wrong is worse than none. A test fails when the files are stale.

    cd apps/api && python -m coldops.cli knowledge --output ../../docs/knowledge
"""

from __future__ import annotations

import pathlib

HEADER = (
    "<!-- GENERATED by `python -m coldops.cli knowledge` from the code. "
    "Do not edit by hand: edit the code, then regenerate. -->\n\n"
)


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


# --------------------------------------------------------------------- findings
def findings_md() -> str:
    from coldops.intelligence import composer, references, vernacular

    problem = composer._PROBLEM_DETAIL
    solution = composer._SOLUTION_DETAIL
    upside = composer._UPSIDE_DETAIL
    capability = composer._CAPABILITY_BY_ISSUE
    issues = sorted(set(problem) | set(solution) | set(upside) | set(capability))
    engine_names = {
        "conversion": "A · conversion (a lost customer)",
        "quality": "B · quality (honest, smaller)",
        "operational": "C · automation (a measured operational gap)",
    }

    out = [
        HEADER,
        "# Website findings\n\n",
        "Every kind of defect ColdOps can find on a business's website, in the words "
        "its emails use: what is wrong, what fixing it does, what it is worth to the "
        "business, and the published sources behind the claim. A message only ever "
        "names a finding that was measured on that business's own site.\n\n",
        f"{len(issues)} finding types.\n\n",
    ]
    for issue in issues:
        engine = vernacular.engine_for(issue).value
        out.append(f"## `{issue}`\n\n")
        out.append(f"- **Message engine:** {engine_names.get(engine, engine)}\n")
        if issue in problem:
            out.append(f"- **What is wrong:** {_cell(problem[issue])}\n")
        if issue in solution:
            out.append(f"- **The fix:** {_cell(solution[issue])}\n")
        if issue in upside:
            out.append(f"- **What it is worth:** {_cell(upside[issue])}\n")
        if issue in capability:
            out.append(f"- **What we offer:** {_cell(capability[issue])}\n")
        refs = references.REFERENCES.get(issue, ())
        if refs:
            out.append("- **Sources:**\n")
            for ref in refs:
                out.append(f"  - {ref.publisher}: [{ref.title}]({ref.url})\n")
        out.append("\n")
    return "".join(out)


# ------------------------------------------------------------------- industries
def industries_md() -> str:
    from coldops.intelligence import playbooks, vernacular, verticals

    out = [
        HEADER,
        "# Industries\n\n",
        "How ColdOps approaches each kind of business: which pages it reads first, "
        "which defects matter most there, what it can offer, what it must never "
        "claim, the words the industry uses about its own customers, and the "
        "Google Maps searches that find more of them.\n\n",
    ]
    vocab = vernacular.VERNACULARS
    for industry, book in sorted(playbooks.PLAYBOOKS.items(), key=lambda kv: kv[1].name):
        out.append(f"## {book.name}\n\n{_cell(book.description)}\n\n")
        out.append(
            "**Pages read first:** "
            + ", ".join(f"`{p}`" for p in book.priority_paths)
            + "\n\n"
        )
        if book.priorities:
            out.append("**What matters most here:**\n\n")
            for p in book.priorities:
                out.append(f"- {_cell(p.label)} (`{p.key}`, {p.category.value})\n")
            out.append("\n")
        if book.offers:
            out.append(
                "| Offer | What it delivers | Needs a finding of type | Est. value |\n"
            )
            out.append("|---|---|---|---|\n")
            for o in book.offers:
                needs = ", ".join(f"`{t}`" for t in sorted(o.requires_finding_types))
                out.append(
                    f"| {_cell(o.label)} | {_cell(o.delivers)} | {needs} | "
                    f"${o.estimated_value_usd:,.0f} |\n"
                )
            out.append("\n")
        if book.prohibited_claims:
            out.append("**Never claim:**\n\n")
            for c in book.prohibited_claims:
                out.append(f"- {_cell(c)}\n")
            out.append("\n")
        v = vocab.get(industry)
        if v is not None:
            out.append("**In their words:**\n\n")
            out.append(
                f"- Called a *{_cell(v.noun)}*; the page that matters is the *{_cell(v.money_page)}*.\n"
            )
            out.append(
                f"- Why a conversion defect matters to them: {_cell(v.conversion_consequence)}\n"
            )
            out.append(
                f"- Why a quality defect matters: {_cell(v.quality_consequence)}\n"
            )
            out.append(
                f"- Why an operational gap matters: {_cell(v.automation_consequence)}\n"
            )
            out.append("\n")
        searches = verticals.verticals_for(industry)
        if searches:
            out.append(
                "**Searches that find them:** "
                + ", ".join(_cell(s) for s in searches)
                + "\n\n"
            )
    return "".join(out)


# ---------------------------------------------------------------------- scoring
def scoring_md() -> str:
    from coldops.intelligence import scoring

    out = [
        HEADER,
        "# How a lead is scored\n\n",
        f"Policy version `{scoring.SCORING_POLICY_VERSION}`. Each lead is scored out of "
        "100 from the parts below, then penalties are taken off. A campaign's bar "
        "(70 unless configured otherwise) decides who is written to. A trained "
        "lead-propensity model (M3) may replace this score only once it beats it "
        "on held-out leads, with the operator's approval.\n\n",
        "| Part | Weight |\n|---|---|\n",
    ]
    for name, weight in sorted(scoring.WEIGHTS.items(), key=lambda kv: -kv[1]):
        out.append(f"| {name.replace('_', ' ')} | {weight:g} |\n")
    out.append(f"| **Total** | **{sum(scoring.WEIGHTS.values()):g}** |\n\n")
    out.append(
        f"Penalties: compliance risk -{scoring.COMPLIANCE_RISK_PENALTY:g}, "
        f"outreach risk -{scoring.OUTREACH_RISK_PENALTY:g}.\n"
    )
    return "".join(out)


# ---------------------------------------------------------------------- replies
def replies_md() -> str:
    from coldops.db.enums import HUMAN_REPLY_CLASSES, ReplyClass
    from coldops.intelligence.intent import NEGATIVE_CLASSES, POSITIVE_CLASSES

    out = [
        HEADER,
        "# How a reply is read\n\n",
        "Every message that arrives in a sending mailbox is classified. A reply "
        "from a person stops that lead's sequence at once. Positive replies wake "
        "the operator; negative ones are filed. The rules are keyword-based, and a "
        "model-based reader runs beside them in shadow, deciding nothing until it "
        "beats them on labelled replies and the operator promotes it.\n\n",
        "| Class | A person? | Direction |\n|---|---|---|\n",
    ]
    for rc in ReplyClass:
        direction = (
            "positive"
            if rc in POSITIVE_CLASSES
            else "negative"
            if rc in NEGATIVE_CLASSES
            else "—"
        )
        human = "yes" if rc in HUMAN_REPLY_CLASSES else "no"
        out.append(f"| `{rc.value}` | {human} | {direction} |\n")
    out.append(
        "\nMail from ColdOps's own addresses -- sending mailboxes, warm-up partners, "
        "test inboxes, the operator -- is never attributed to a lead.\n"
    )
    return "".join(out)


# ------------------------------------------------------------------- send rules
def send_rules_md() -> str:
    from coldops.delivery import placement_gate, readiness
    from coldops.policy.engine import OPERATOR_TEST_EXEMPT, REPLY_EXEMPT, DenyCode

    temporary = {
        DenyCode.QUOTA_EXHAUSTED,
        DenyCode.QUIET_HOURS,
        DenyCode.OUTSIDE_SEND_WINDOW,
        DenyCode.SPACING,
    }
    out = [
        HEADER,
        "# When mail is refused\n\n",
        "Every email is checked again at the moment it would be sent, against the "
        "state of things then -- not when it was drafted. Every refusal is "
        "recorded with its reason. *Temporary* refusals wait and retry. A refusal "
        "only because the email's mailbox is switched off moves it to a mailbox "
        "that is on, or waits for one. Everything else blocks for good.\n\n",
        "| Refusal | Kind | Lifted for a reply? | Lifted for the operator's test? |\n",
        "|---|---|---|---|\n",
    ]
    for code in DenyCode:
        out.append(
            f"| `{code.value}` | {'temporary' if code in temporary else 'block'} | "
            f"{'yes' if code in REPLY_EXEMPT else 'no'} | "
            f"{'yes' if code in OPERATOR_TEST_EXEMPT else 'no'} |\n"
        )
    out.append(
        "\n## Inbox placement\n\n"
        f"A mailbox sends cold mail only while at least {placement_gate.FLOOR:.0%} "
        "of its recent inbox tests landed in the inbox, measured within the last "
        f"{int(placement_gate.FRESH_WITHIN.total_seconds() // 3600)} hours. Two "
        "consecutive days under that on any mailbox rests the whole domain for "
        f"{placement_gate.DOMAIN_REST.days} days.\n\n"
        "## Switching cold mail back on\n\n"
        f"The operator's bar: every measured day at least {readiness.DAILY_FLOOR:.0%} "
        f"inbox over {readiness.STREAK_DAYS} days, at least "
        f"{readiness.MIN_MEASURED_DAYS} days measured, the domain not resting, the "
        "gate clear today. `coldops reactivate` and the CRM's System page check it.\n"
    )
    return "".join(out)


# ------------------------------------------------------------------------ index
FILES = {
    "findings.md": ("Website findings", findings_md),
    "industries.md": ("Industries", industries_md),
    "scoring.md": ("How a lead is scored", scoring_md),
    "replies.md": ("How a reply is read", replies_md),
    "send-rules.md": ("When mail is refused", send_rules_md),
}


def readme_md() -> str:
    lines = [
        HEADER,
        "# ColdOps knowledge base\n\n",
        "What ColdOps knows, generated from the code that acts on it. Regenerate:\n\n",
        "```\ncd apps/api && python -m coldops.cli knowledge --output ../../docs/knowledge\n```\n\n",
    ]
    for name, (title, _) in FILES.items():
        lines.append(f"- [{title}]({name})\n")
    return "".join(lines)


def render_all() -> dict[str, str]:
    files = {name: build() for name, (_, build) in FILES.items()}
    files["README.md"] = readme_md()
    return files


def write(directory: pathlib.Path) -> list[pathlib.Path]:
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for name, content in render_all().items():
        path = directory / name
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(path)
    return written


__all__ = ["FILES", "render_all", "write"]
